package foms.enums;


/**
 * Represents the roles of users in the system.
 *
 * The UserRole enum defines the possible roles:
 * <ul>
 *     <li>{@link #A Admin}</li>
 *     <li>{@link #M Manager}</li>
 *     <li>{@link #S Staff}</li>
 *     <li>{@link #C Customer}</li>
 * </ul>
 *
 * @author  Kua Li Min
 * @version 1.0
 * @since   2024-04-15
 */

public enum UserRole {
    /**
     * Represents an Admin user role.
     */
    A,
    
    /**
     * Represents a Manager user role.
     */
    M,
    
    /**
     * Represents a Staff user role.
     */
    S,
    
    /**
     * Represents a Customer user role.
     */
    C
}